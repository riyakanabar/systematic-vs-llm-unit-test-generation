def fixed_knot_LP(pc_linear_fx, epsilon):
    """
    Computes the optimal piecewise linear approximation with minimal number of pieces
    such that the maximum vertical deviation (infinity norm) is at most epsilon.

    Args:
    pc_linear_fx (list of tuples): List of (x, y) points defining the original piecewise linear function.
                                   Assumes x values are strictly increasing.
    epsilon (float): Tolerance for the infinity norm error.

    Returns:
    tuple: (optimal_pc_linear_fx, optimal_num_pieces, given_num_pieces)
           - optimal_pc_linear_fx: List of (x, y) points for the approximation.
           - optimal_num_pieces: Number of pieces in the approximation.
           - given_num_pieces: Number of pieces in the input.
    """
    points = pc_linear_fx
    m = len(points)
    if m < 2:
        return points, 0, 0

    given_num_pieces = m - 1

    x_list = [p[0] for p in points]
    y_list = [p[1] for p in points]

    INF = float('inf')
    dp = [INF] * m
    prev = [-1] * m
    lo_y = [0.0] * m
    hi_y = [0.0] * m

    dp[0] = 0
    lo_y[0] = y_list[0] - epsilon
    hi_y[0] = y_list[0] + epsilon

    for j in range(1, m):
        min_cost = INF
        union_lo = INF
        union_hi = -INF
        best_prev = -1

        for i in range(j):
            if dp[i] == INF:
                continue
            lo_end, hi_end = get_end_interval(i, j, points, epsilon, lo_y[i], hi_y[i])
            if lo_end is None:
                continue

            new_cost = dp[i] + 1
            if new_cost < min_cost:
                min_cost = new_cost
                union_lo = lo_end
                union_hi = hi_end
                best_prev = i
            elif new_cost == min_cost:
                union_lo = min(union_lo, lo_end)
                union_hi = max(union_hi, hi_end)
                # best_prev remains the same

        if min_cost < INF:
            dp[j] = min_cost
            lo_y[j] = union_lo
            hi_y[j] = union_hi
            prev[j] = best_prev

    optimal_num_pieces = int(dp[m - 1]) if dp[m - 1] < INF else given_num_pieces

    # Reconstruct kept indices
    kept = []
    current = m - 1
    while current >= 0:
        kept.append(current)
        if prev[current] == -1:
            break
        current = prev[current]
    kept.reverse()

    # Now solve global LP for y_primes
    num_kept = len(kept)
    if num_kept == 1:
        # Only one point
        y_prime = [y_list[kept[0]]]  # but adjust? but no segments
        optimal_pc_linear_fx = [(x_list[kept[0]], y_list[kept[0]])]
    else:
        num_pieces = num_kept - 1
        num_constraints = 0
        for r in range(num_pieces):
            a = kept[r]
            b = kept[r + 1]
            num_k = b - a + 1
            num_constraints += 2 * num_k

        A_ub_list = []
        b_ub_list = []

        for r in range(num_pieces):
            a = kept[r]
            b = kept[r + 1]
            dx = x_list[b] - x_list[a]
            if dx == 0:
                # degenerate, but skip or handle
                continue
            for kk in range(a, b + 1):
                t = 0.0 if kk == a else (x_list[kk] - x_list[a]) / dx
                # upper
                row = np.zeros(num_kept)
                row[r] = 1 - t
                row[r + 1] = t
                A_ub_list.append(row)
                b_ub_list.append(y_list[kk] + epsilon)
                # lower
                row = np.zeros(num_kept)
                row[r] = -(1 - t)
                row[r + 1] = -t
                A_ub_list.append(row)
                b_ub_list.append(-(y_list[kk] - epsilon))

        if len(A_ub_list) == 0:
            optimal_pc_linear_fx = [(x_list[idx], y_list[idx]) for idx in kept]
        else:
            A_ub = np.vstack(A_ub_list)
            b_ub = np.array(b_ub_list)
            c = np.zeros(num_kept)
            res = linprog(c, A_ub=A_ub, b_ub=b_ub, bounds=(None, None), method='highs')
            if res.success:
                y_primes = res.x
                optimal_pc_linear_fx = [(x_list[idx], y_primes[p]) for p, idx in enumerate(kept)]
            else:
                # Fallback to original if somehow infeasible
                optimal_pc_linear_fx = points
                optimal_num_pieces = given_num_pieces

    return optimal_pc_linear_fx, optimal_num_pieces, given_num_pieces


def compute_min_E_and_fit(i, j, points):
    """Compute minimax (Chebyshev) fit and minimum E for points[i:j+1]."""
    if j - i < 1:
        return 0.0, None, None
    x = np.array([p[0] for p in points[i:j+1]])
    y = np.array([p[1] for p in points[i:j+1]])
    n = j - i + 1
    A_ub = np.zeros((2*n, 3))
    b_ub = np.zeros(2*n)
    for k in range(n):
        # a * x_k + b - E <= y_k
        A_ub[2*k, 0] = x[k]
        A_ub[2*k, 1] = 1.0
        A_ub[2*k, 2] = -1.0
        b_ub[2*k] = y[k]
        # -a * x_k - b - E <= -y_k
        A_ub[2*k+1, 0] = -x[k]
        A_ub[2*k+1, 1] = -1.0
        A_ub[2*k+1, 2] = -1.0
        b_ub[2*k+1] = -y[k]
    c = np.array([0.0, 0.0, 1.0])
    res = linprog(c, A_ub=A_ub, b_ub=b_ub, bounds=(None, None), method='highs')
    if res.success:
        return res.fun, res.x[0], res.x[1]
    else:
        return float('inf'), None, None

def reconstruct_optimal_points(points, kept, epsilon):
    """Reconstruct the optimal piecewise linear function from kept indices."""
    x_list = [p[0] for p in points]
    y_list = [p[1] for p in points]
    num_kept = len(kept)
    if num_kept < 2:
        return [(x_list[kept[0]], y_list[kept[0]])] if num_kept == 1 else [], 0
    num_pieces = num_kept - 1
    A_ub_list = []
    b_ub_list = []
    for r in range(num_pieces):
        a = kept[r]
        b = kept[r + 1]
        dx = x_list[b] - x_list[a]
        if dx == 0:
            continue
        for kk in range(a, b + 1):
            t = 0.0 if kk == a else (x_list[kk] - x_list[a]) / dx
            # upper: (1-t)*y_a + t*y_b <= y_kk + epsilon
            row = np.zeros(num_kept)
            row[r] = 1 - t
            row[r + 1] = t
            A_ub_list.append(row)
            b_ub_list.append(y_list[kk] + epsilon)
            # lower: -(1-t)*y_a - t*y_b <= -(y_kk - epsilon)
            row = np.zeros(num_kept)
            row[r] = -(1 - t)
            row[r + 1] = -t
            A_ub_list.append(row)
            b_ub_list.append(-(y_list[kk] - epsilon))
    if not A_ub_list:
        return [(x_list[idx], y_list[idx]) for idx in kept]
    A_ub = np.vstack(A_ub_list)
    b_ub = np.array(b_ub_list)
    c = np.zeros(num_kept)
    res = linprog(c, A_ub=A_ub, b_ub=b_ub, bounds=(None, None), method='highs')
    if res.success:
        y_primes = res.x
        return [(x_list[idx], y_primes[p]) for p, idx in enumerate(kept)]
    else:
        return points


def greedy_farthest(pc_linear_fx, epsilon):
    """Greedy Farthest with Minimax Check"""
    points = pc_linear_fx
    m = len(points)
    if m < 2:
        return points, 0, 0
    given_num_pieces = m - 1
    kept = [0]
    current = 0
    while current < m - 1:
        found = False
        for j in range(m - 1, current, -1):
            min_E, _, _ = compute_min_E_and_fit(current, j, points)
            if min_E <= epsilon:
                kept.append(j)
                current = j
                found = True
                break
        if not found:
            kept.append(m - 1)
            break
    optimal_pc_linear_fx = reconstruct_optimal_points(points, kept, epsilon)
    optimal_num_pieces = len(optimal_pc_linear_fx) - 1 if len(optimal_pc_linear_fx) > 1 else 0
    if len(optimal_pc_linear_fx) != len(kept):
        optimal_pc_linear_fx = points
        optimal_num_pieces = given_num_pieces
    return optimal_pc_linear_fx, optimal_num_pieces, given_num_pieces


def recursive_keep_minimax(i, j, points, epsilon):
    """Recursive function for top-down splitting with minimax check."""
    if i >= j:
        return []
    if i + 1 == j:
        return [i, j]
    min_E, a, b = compute_min_E_and_fit(i, j, points)
    if min_E <= epsilon:
        return [i, j]
    x = np.array([p[0] for p in points[i:j+1]])
    y = np.array([p[1] for p in points[i:j+1]])
    pred = a * x + b
    devs = np.abs(y - pred)
    k = i + 1 + np.argmax(devs[1:-1])
    left = recursive_keep_minimax(i, k, points, epsilon)
    right = recursive_keep_minimax(k, j, points, epsilon)
    return left + right[1:]

def top_down_split(pc_linear_fx, epsilon):
    """Top-Down Split with Minimax Check"""
    points = pc_linear_fx
