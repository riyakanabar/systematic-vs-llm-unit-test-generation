from typing import List, Tuple
import numpy as np
from scipy.optimize import linprog


Point = Tuple[float, float]
def _y_on_line(x, x1, y1, x2, y2):
    t = (x - x1) / (x2 - x1)
    return y1 + t * (y2 - y1)
def _feasible_fixed_endpoints(pts: List[Point], i: int, j: int, eps: float) -> bool:
    x1, y1 = pts[i]; x2, y2 = pts[j]
    if x2 == x1:  # should not happen with strictly increasing x
        return False
    for k in range(i + 1, j):
        xk, yk = pts[k]
        yhat = _y_on_line(xk, x1, y1, x2, y2)
        if abs(yk - yhat) > eps:
            return False
    return True
def shortest_path_dp(pc_linear_fx: List[Point], epsilon: float):
    pts = pc_linear_fx
    n = len(pts) - 1
    # Build visibility list nexts[i] = {j>i | segment i->j feasible}
    nexts = [[] for _ in range(n + 1)]
    for i in range(n):
        j = i + 1
        while j <= n and _feasible_fixed_endpoints(pts, i, j, epsilon):
            nexts[i].append(j)
            j += 1

    # Shortest path on DAG
    INF = 10**9
    dp = [INF] * (n + 1)
    prev = [-1] * (n + 1)
    dp[0] = 0
    for i in range(n):
        if dp[i] == INF:
            continue
        for j in nexts[i]:
            if dp[i] + 1 < dp[j]:
                dp[j] = dp[i] + 1
                prev[j] = i

    # Reconstruct
    if dp[n] == INF:
        raise RuntimeError("No feasible simplification within epsilon.")
    idx = []
    cur = n
    while cur != -1:
        idx.append(cur)
        cur = prev[cur]
    idx.reverse()

    optimal_pc = [pts[k] for k in idx]
    optimal_num_pieces = len(optimal_pc) - 1
    given_num_pieces = n
    return optimal_pc, optimal_num_pieces, given_num_pieces



def get_end_interval(i, j, points, epsilon, lo_start, hi_start):
    """
    Compute the feasible interval for y_j' for the segment from i to j,
    with y_i' constrained to [lo_start, hi_start].
    Returns (lo_end, hi_end) or (None, None) if infeasible.
    """
    if i >= j:
        return None, None

    x_list = [p[0] for p in points]
    y_list = [p[1] for p in points]

    dx = x_list[j] - x_list[i]
    if dx == 0:
        return None, None  # degenerate

    num_k = j - i + 1
    num_cons_base = 2 * num_k
    num_cons = num_cons_base + 2  # + bounds on y_start

    A_ub = np.zeros((num_cons, 2))
    b_ub = np.zeros(num_cons)

    cons_idx = 0
    for kk in range(i, j + 1):
        t = 0.0 if kk == i else (x_list[kk] - x_list[i]) / dx
        # upper: (1-t)*y_start + t*y_end <= y_kk + epsilon
        A_ub[cons_idx, 0] = 1 - t
        A_ub[cons_idx, 1] = t
        b_ub[cons_idx] = y_list[kk] + epsilon
        cons_idx += 1
        # lower: -(1-t)*y_start - t*y_end <= -(y_kk - epsilon)
        A_ub[cons_idx, 0] = -(1 - t)
        A_ub[cons_idx, 1] = -t
        b_ub[cons_idx] = -(y_list[kk] - epsilon)
        cons_idx += 1

    # bound y_start <= hi_start
    A_ub[cons_idx, 0] = 1.0
    A_ub[cons_idx, 1] = 0.0
    b_ub[cons_idx] = hi_start
    cons_idx += 1
    # bound -y_start <= -lo_start
    A_ub[cons_idx, 0] = -1.0
    A_ub[cons_idx, 1] = 0.0
    b_ub[cons_idx] = -lo_start

    # Check feasibility
    c_feas = np.array([0.0, 0.0])
    res_feas = linprog(c_feas, A_ub=A_ub, b_ub=b_ub, bounds=(None, None), method='highs')
    if not res_feas.success:
        return None, None

    # Min y_end
    c_min = np.array([0.0, 1.0])
    res_min = linprog(c_min, A_ub=A_ub, b_ub=b_ub, bounds=(None, None), method='highs')
    if not res_min.success:
        return None, None
    lo_end = res_min.fun

    # Max y_end = -min (-y_end)
    c_max = np.array([0.0, -1.0])
    res_max = linprog(c_max, A_ub=A_ub, b_ub=b_ub, bounds=(None, None), method='highs')
    if not res_max.success:
        return None, None
    hi_end = -res_max.fun

    if lo_end > hi_end + 1e-10:  # numerical tolerance
        return None, None

    return lo_end, hi_end

